const H = require('./helpers.cjs');
const { chromium } = require('playwright');
const SP = process.env.SP;
(async () => {
  const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
  const ctx = await browser.newContext({ viewport: { width: 1180, height: 820 }, deviceScaleFactor: 1 });
  const page = await ctx.newPage();
  const errs = [];
  page.on('pageerror', (e) => errs.push(e.message));
  await page.route('**/three.min.js', (r) => r.fulfill({ path: SP + '/three/node_modules/three/build/three.min.js', contentType: 'application/javascript' }));
  await H.routes(page);
  await page.route(/fonts\.(googleapis|gstatic)\.com/, (r) => r.abort());
  await page.goto('file:///home/user/opencode-mobile/faro/faro.html');
  await H.compat(page);
  await page.waitForTimeout(700);
  await page.evaluate((m) => { window.FARO.setOption('mode', m); window.FARO.startGame(); }, 'duel');
  await page.waitForTimeout(400);
  const info = await page.evaluate(() => {
    const app = window.FARO; const g = app.game;
    g.bots.forEach((b) => { b.update = () => {}; });
    const center = g.map.get(0, 0);
    const near = (k, mover) => g.freeCellsNear(center.i, mover, 0, k);
    const land = near(30, 'land');
    const sea = near(14, 'sea');
    const mk = (pid, type, ci) => g.addUnit(pid, type, ci);
    const mine = []; const theirs = [];
    ['tank', 'rifle', 'rifle', 'rocket', 'jeep', 'sniper', 'aa'].forEach((t, i) => mine.push(mk(0, t, land[i])));
    ['rifle', 'rifle', 'tank', 'rocket', 'rifle', 'jeep'].forEach((t, i) => theirs.push(mk(1, t, land[12 + i])));
    mine.push(mk(0, 'heli', land[3]));
    theirs.push(mk(1, 'destroyer', sea[6]));
    mine.push(mk(0, 'speedboat', sea[0]));
    theirs.push(mk(1, 'heli', land[20]));
    const turretCell = land.find((ci) => !g.cells[ci].bld && g.cells[ci].t !== 'gold');
    g.addBuilding(1, 'turret', land[25], true);
    g.orderMove(mine.filter((u) => u.mover === 'land'), land[14], true);
    g.orderMove(theirs.filter((u) => u.mover === 'land'), land[2], true);
    app.renderer.cam.tx = center.x; app.renderer.cam.tz = center.z; app.renderer.cam.dist = 17;
    app.setSelection(mine.filter((u) => u.mover === 'land'));
    for (let i = 0; i < 25; i++) g.update(0.1);
    return { mine: mine.length, theirs: theirs.length };
  });
  console.log(JSON.stringify(info));
  await page.waitForTimeout(150);
  await page.screenshot({ path: SP + '/shots/32-fight.png' });
  await page.evaluate(() => { const g = window.FARO.game; for (let i = 0; i < 40; i++) g.update(0.1); });
  await page.waitForTimeout(120);
  await page.screenshot({ path: SP + '/shots/33-fight2.png' });
  const after = await page.evaluate(() => { const g = window.FARO.game; return { p0: g.units.filter((u) => u.owner === 0).length, p1: g.units.filter((u) => u.owner === 1).length }; });
  console.log('after', JSON.stringify(after), 'errores', JSON.stringify(errs));
  await browser.close();
})();
